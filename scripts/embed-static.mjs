// Embeds public/* into src/static.generated.ts so the Worker can serve the
// dashboard itself. (Workers Static Assets upload uses a JWT in the
// Authorization header, which the cloud dev environment's proxy overwrites.)
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative, extname } from "node:path";

const root = new URL("../public/", import.meta.url).pathname;
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".json": "application/json", ".svg": "image/svg+xml", ".txt": "text/plain; charset=utf-8", ".webmanifest": "application/manifest+json" };
const files = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = "/" + relative(root, p).split("\\").join("/");
    const body = readFileSync(p, "utf8");
    files[rel] = { type: TYPES[extname(name)] ?? "application/octet-stream", body, etag: `"${createHash("sha1").update(body).digest("hex").slice(0, 16)}"` };
  }
}
walk(root);
const out = `// GENERATED by scripts/embed-static.mjs — do not edit.\nexport const STATIC_FILES: Record<string, { type: string; body: string; etag: string }> = ${JSON.stringify(files, null, 0)};\n`;
writeFileSync(new URL("../src/static.generated.ts", import.meta.url), out);
console.log(`embedded ${Object.keys(files).length} files (${(out.length / 1024).toFixed(0)} KB)`);
